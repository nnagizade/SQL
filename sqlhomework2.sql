--task 1
SELECT MANAGER_ID, COUNT(*) AS ISCI_SAYI FROM HR.EMPLOYEES
GROUP BY MANAGER_ID;
--TASK 2
SELECT COUNTRY_ID, COUNT(*) AS OFIS_SAYI FROM HR.LOCATIONS
GROUP BY COUNTRY_ID;
--TASK 3
SELECT E.FIRST_NAME,E.LAST_NAME,D.JOB_TITLE
FROM HR.EMPLOYEES E
JOIN HR.JOBS D
ON E.JOB_ID=D.JOB_ID;
--TASK 4
SELECT DEPARTMENT_ID, ROUND(AVG(SALARY),2) AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING ROUND(AVG(SALARY),2) > 8000;
--TASK 5
SELECT DEPARTMENT_ID, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE SALARY > 3000
GROUP BY DEPARTMENT_ID
FETCH FIRST 3 ROWS ONLY;
