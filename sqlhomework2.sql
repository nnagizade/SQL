--task 1
SELECT MANAGER_ID, COUNT(*) AS ISCI_SAYI FROM HR.EMPLOYEES
GROUP BY MANAGER_ID;
--TASK 2
SELECT COUNTRY_ID, COUNT(*) AS OFIS_SAYI FROM HR.LOCATIONS
GROUP BY COUNTRY_ID;
--TASK 3
SELECT E.FIRST_NAME,E.LAST_NAME,D.JOB_TITLE
FROM HR.EMPLOYEES E
JOIN HR.JOBS D
ON E.JOB_ID=D.JOB_ID;
--TASK 4
SELECT DEPARTMENT_ID, ROUND(AVG(SALARY),2) AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING ROUND(AVG(SALARY),2) > 8000;
--TASK 5
SELECT DEPARTMENT_ID, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE SALARY > 3000
GROUP BY DEPARTMENT_ID
FETCH FIRST 3 ROWS ONLY;
--TASK 6
SELECT D.JOB_TITLE, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES E
JOIN HR.JOBS D
ON E.JOB_ID = D.JOB_ID
GROUP BY D.JOB_TITLE
ORDER BY ISCI_SAYI DESC;
--TASK 7
SELECT E.CITY, E.COUNTRY_ID
FROM HR.LOCATIONS E
LEFT JOIN HR.DEPARTMENTS D 
ON E.LOCATION_ID = D.LOCATION_ID
WHERE D.DEPARTMENT_ID IS NULL;
--TASK 8
SELECT J.JOB_TITLE, AVG(E.SALARY) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.JOBS J ON E.JOB_ID = J.JOB_ID
GROUP BY J.JOB_TITLE
HAVING AVG(E.SALARY) > 10000;
--TASK 9
SELECT L.CITY, COUNT(E.EMPLOYEE_ID) AS ISCI_SAYI, ROUND(AVG(E.SALARY)) AS ORTA_MAAS
FROM HR.LOCATIONS L
JOIN HR.DEPARTMENTS D 
ON L.LOCATION_ID = D.LOCATION_ID
JOIN HR.EMPLOYEES E 
ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY L.CITY
HAVING COUNT(E.EMPLOYEE_ID) > 5
ORDER BY ISCI_SAYI DESC;
--TASK 10
SELECT D.DEPARTMENT_NAME, COUNT(E.EMPLOYEE_ID) AS ISCI_SAYI
FROM HR.DEPARTMENTS D
LEFT JOIN HR.EMPLOYEES E 
ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
ORDER BY ISCI_SAYI DESC, D.DEPARTMENT_NAME ASC;
