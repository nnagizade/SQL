SELECT FIRST_NAME, DEPARTMENT_ID,
       NVL2(DEPARTMENT_ID, 'Sobe var', 'Sobe teyin olunmayib') AS SOBE_STATUSU
FROM HR.EMPLOYEES;
--task 4
SELECT JOB_ID, JOB_TITLE,
       CASE
           WHEN JOB_ID IN ('AD_PRES', 'AD_VP', 'FI_MGR', 'AC_MGR') THEN 'Ali Rehberlik'
           WHEN JOB_ID IN ('IT_PROG', 'SA_REP', 'FI_ACCOUNT') THEN 'Esas Mutexessis'
           WHEN JOB_ID IN ('AD_PRES', 'AD_VP', 'FI_MGR', 'AC_MGR') THEN 'Operativ Isci'
           ELSE 'Diger'
       END AS  KATEQORIYA
FROM HR.JOBS;
--TASK 5
SELECT FIRST_NAME, DEPARTMENT_ID, SALARY,
       CASE
           WHEN DEPARTMENT_ID = 50 THEN SALARY*0.08
           WHEN DEPARTMENT_ID = 30 THEN SALARY*0.12
           WHEN DEPARTMENT_ID = 100 THEN 400
           ELSE SALARY*0.04
       END AS  MUAVINET
FROM HR.EMPLOYEES
ORDER BY MUAVINET ASC;
--TASK 6
SELECT FIRST_NAME, COMMISSION_PCT,
       CASE
           WHEN COMMISSION_PCT IS NULL  THEN 'Yoxdur'
           WHEN COMMISSION_PCT > 0.25  THEN 'Yuksek komissiya'
           ELSE 'Normal komissiya'
       END AS 'Komissiya novu'
FROM HR.EMPLOYEES;
--TASK 7
SELECT FIRST_NAME, PHONE_NUMBER, SALARY,
       CASE
           WHEN PHONE_NUMBER LIKE '1515%' THEN 'Daxili xett'
           WHEN SALARY >= 10000 THEN 'Yuksek maasli'
           WHEN COMMISSION_PCT IS NOT NULL THEN 'Satis komandasi'
           ELSE 'Standart isci'
       END AS  KATEQORIYA
FROM HR.EMPLOYEES;
--TASK 8
SELECT FIRST_NAME, SALARY, COMMISSION_PCT,
       SALARY * NVL(COMMISSION_PCT, 0)*3 AS RUBLUK_BONUS,
       (SALARY * 3)+SALARY * NVL(COMMISSION_PCT, 0)*3 AS RUBLUK_UMUMI
FROM HR.EMPLOYEES
ORDER BY RUBLUK_UMUMI ASC;
--TASK 9
SELECT E.FIRST_NAME,D.JOB_TITLE,E.SALARY,D.MIN_SALARY, D.MAX_SALARY,
       CASE 
           WHEN E.SALARY = D.MAX_SALARY THEN 'Limite catib'
           WHEN D.MAX_SALARY - E.SALARY <= 2000 THEN 'Limite cox yaxin'
           WHEN E.SALARY < D.MIN_SALARY + 1000 THEN 'Baslangic seviyyede'
           ELSE 'Orta araliqda'
       END AS MAAS_VEZIYYETI
FROM HR.EMPLOYEES E
JOIN HR.JOBS D ON E.JOB_ID = D.JOB_ID;
--TASK 10
SELECT E.FIRST_NAME,E.LAST_NAME,
       NVL2(D.MANAGER_ID, 'Rehberi var', 'Rehbersiz sobe') AS MENECER_STATUSU,
       CASE 
           WHEN D.DEPARTMENT_ID IS NULL THEN 'Teyin edilmeyib'
           WHEN L.COUNTRY_ID = 'US'  THEN 'ABS ofisi'
           ELSE 'Beynelxalq ofis'
       END AS REGION
FROM HR.EMPLOYEES E
LEFT JOIN HR.DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
LEFT JOIN HR.LOCATIONS L   ON D.LOCATION_ID = L.LOCATION_ID;
