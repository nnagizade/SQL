SELECT FIRST_NAME, LAST_NAME, JOB_ID, SALARY
FROM HR.EMPLOYEES
WHERE JOB_ID IN (
    SELECT JOB_ID 
    FROM HR.JOBS 
    WHERE MAX_SALARY > 15000
);
--TASK 8
SELECT FIRST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (
    SELECT DEPARTMENT_ID
    FROM HR.DEPARTMENTS
    WHERE UPPER(DEPARTMENT_NAME) IN ('IT', 'FINANCE')
);
--TASK 9
SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME
FROM HR.EMPLOYEES
WHERE EMPLOYEE_ID NOT IN (
    SELECT MANAGER_ID 
    FROM HR.EMPLOYEES 
    WHERE MANAGER_ID IS NOT NULL
);
--TASK 10
SELECT 
    M.FIRST_NAME AS MENECER_ADI, 
    M.LAST_NAME AS MENECER_SOYADI, 
    MAX(E.SALARY) AS MAX_TABE_MAASI, 
    MIN(E.SALARY) AS MIN_TABE_MAASI
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID
GROUP BY M.FIRST_NAME, M.LAST_NAME
HAVING AVG(E.SALARY) > 7000
ORDER BY MAX_TABE_MAASI DESC;











