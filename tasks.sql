--TASK 1
SELECT FIRST_NAME, LAST_NAME, HIRE_DATE,
       CASE
           WHEN HIRE_DATE < TO_DATE('2003-01-01', 'YYYY-MM-DD') THEN 'VETERAN'
           WHEN HIRE_DATE BETWEEN TO_DATE('2003-01-01', 'YYYY-MM-DD') 
                    AND TO_DATE('2006-12-31', 'YYYY-MM-DD') THEN 'TECRUBELI'
           ELSE 'YENI'
       END AS STAJ_QRUPU
FROM HR.EMPLOYEES;
--TASK 2
SELECT DEPARTMENT_ID, DEPARTMENT_NAME,
       CASE
           WHEN DEPARTMENT_NAME = 'Administration' THEN 'Idareetme'
           WHEN DEPARTMENT_NAME = 'Marketing' THEN 'Marketinq'
           WHEN DEPARTMENT_NAME = 'Purchasing' THEN 'Satinalma'
           WHEN DEPARTMENT_NAME = 'Human Resources' THEN 'Insan Resurslari'
           ELSE 'Diger sobe'
       END AS  SOBE_AZ
FROM HR.DEPARTMENTS;
--TASK 3
SELECT FIRST_NAME, DEPARTMENT_ID,
       CASE
           WHEN DEPARTMENT_ID IS NULL THEN 'Sobe teyin olunmayib'
           ELSE 'Sobe var'
       END AS  SOBE_STATUSU
FROM HR.EMPLOYEES;
